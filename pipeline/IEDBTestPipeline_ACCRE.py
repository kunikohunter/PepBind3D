# ======== Default mode: Process all batches locally ========
batchlist = make_batch(fasta_fn, args.batchSize[0] if args.batchSize else None)
print(f"Starting multiprocessing with {args.threads} threads across {len(batchlist)} batches...")
pool = multiprocessing.Pool(args.threads)

for d in batchlist:
	print(f"Threading peptides in {os.path.basename(d)}")
	pool.apply_async(safe_thread_all, (d, mhcdb, args.rosetta[0], args.receptor[0]), dict(params=add_params, for_production=[args.slurm, args.options], ignore_perfect_match=args.ignore_epitope_match, find_worst_template=args.find_worst_template))

pool.close()
pool.join()

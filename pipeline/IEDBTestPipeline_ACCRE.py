def flatten_columns(df):
	if isinstance(df.columns, pd.MultiIndex):
		df.columns = [' '.join(col).strip() for col in df.columns]
	return df

def standardize_columns(df):
	df.columns = (df.columns.str.strip().str.replace(' ', '_').str.replace('/', '-').str.lower())
	return df

def rename_columns(df):
	rename_map = {
        "mhc_restriction_name": "mhc_restriction_name",
        "epitope_source_molecule": "parent_protein_accession",
        "epitope_name": "description",
        "reference_pmid": "pubmed_id",
        "assay_quantitative_measurement": "quantitative_measurement"}

	df.rename(columns=rename_map, inplace=True)
	return df

def clean_peplist(peplist,prefix=""):
	peplist["Flag"] = False # Set a flag value here in case we need to do a manual review

	# Filter data: keep only relevant columns and only rows that contain binding affinity data
	# peplist=peplist[['Epitope_ID','PubMed_ID', 'Description', 'Parent_Protein', 'Parent_Protein_Accession', 'Method-Technique', 'Assay_Group', 'Quantitative_measurement', 'PDB_ID', 'Allele_Name']]

	# Filter data: keep only relevant rows with both Quantitative_Measurement and Assay_Units
	peplist = peplist.dropna(subset=["Quantitative_Measurement", "Assay_Units"])

	# Standardize 'Assay_Response' values
	peplist.loc[:, "Assay_Response_Standardized"] = peplist["Assay_Response_Measured"].replace({"dissociation constant KD (~EC50)": "dissociation constant (KD)", "dissociation constant KD": "dissociation constant (KD)", "dissociation constant KD (~IC50)": "dissociation constant (KD)"})

	# Filter out entries that don't match the valid responses criteria
	valid_responses = ["dissociation constant (KD)", "half maximal inhibitory concentration (IC50)"]
	peplist = peplist[peplist["Assay_Response_Standardized"].isin(valid_responses)].copy()

	start_len=len(peplist)
	print(f'{start_len} starting records')

	if "Epitope_ID" not in peplist.columns:
		raise KeyError("Missing expected column 'Epitope ID' after renaming. Check source or renaming logic.")

	enames = peplist["Epitope_ID"].unique()
	print(f'{len(enames)} unique epitope IDs')
	print("Filtering duplicate epitopes...")

	filtered_count=0
	for e in peplist["Epitope_ID"].unique():
		filtered_count += 1
		if filtered_count % 1000 == 0 or filtered_count == len(peplist["Epitope_ID"].unique()):
			print(f"Filtered {filtered_count:<10} of {len(peplist['Epitope_ID'].unique()):<10}", end="\r")

		for assay_type in ["dissociation constant (KD)", "half maximal inhibitory concentration (IC50)"]:
			tmp = peplist[(peplist["Epitope_ID"] == e) & (peplist["Assay_Response_Standardized"] == assay_type)].copy()

			if len(tmp) == 2:
				pubmed_nan = tmp["PubMed_ID"].isna()
				values = tmp["Quantitative_Measurement"].tolist()
				value_diff = abs(values[0] - values[1])

				if pubmed_nan.any() and not pubmed_nan.all():
					# Prefer the one with a PubMed ID
					to_drop = tmp.index[pubmed_nan][0]
					peplist.drop(to_drop, inplace=True)

				elif pubmed_nan.all() and value_diff > 10:
					# Both missing PubMed, and values far apart → drop both
					peplist.drop(tmp.index, inplace=True)

				elif pubmed_nan.all() and value_diff <= 10:
					# Both missing PubMed ID and values are similar → keep one (e.g., the first)
					peplist.drop(tmp.index[1], inplace=True)

				elif tmp["PubMed_ID"].notna().all():
					if value_diff < 10:
						# Both have PubMed, values similar → drop one (arbitrary)
						peplist.drop(tmp.index[0], inplace=True)
					else:
						# Both have PubMed, values conflict → flag
						peplist.loc[tmp.index, "Flag"] = True
				else:
					# All other ambiguous cases → flag
					peplist.loc[tmp.index, "Flag"] = True

			elif len(tmp) > 2:
				pubmed_nan = tmp["PubMed_ID"].isna()
				values = tmp["Quantitative_Measurement"].tolist()

				# Remove entries with missing PubMed IDs first
				drop_ids = tmp[pubmed_nan].index
				peplist.drop(drop_ids, inplace=True)
				tmp = tmp.drop(drop_ids)

				# If there are still entries to process, handle them:
				if len(tmp) > 2:
					# Check if values are within 10 of each other
					value_diff_matrix = np.abs(np.subtract.outer(values, values))
					value_diff_matrix = np.tril(value_diff_matrix, -1)  # Ignore diagonal, we don't compare to self

					if (value_diff_matrix <= 10).sum(axis=1).max() == len(values) - 1:
						# All values are within 10, keep one of the entries (e.g., the first one)
						peplist.drop(tmp.index[1:], inplace=True)
					else:
						# If we have a case where values differ significantly, keep the one closest to the median
						median_value = np.median(values)
						closest_to_median_idx = np.argmin(np.abs(np.array(values) - median_value))
						peplist.drop(tmp.index.difference([tmp.index[closest_to_median_idx]]), inplace=True)

			# Handle cases where we outliers
			elif len(tmp) > 2 and tmp["Quantitative_Measurement"].nunique() > 1:
				# Remove the outlier then take the median of the rest
				values = tmp["Quantitative_Measurement"].tolist()
				outlier_value = max(values)
				tmp_cleaned = tmp[tmp["Quantitative_Measurement"] != outlier_value]
				median_value = np.median(tmp_cleaned["Quantitative_Measurement"])
				# Add back the median value entry
				tmp_cleaned["Quantitative_Measurement"] = median_value
				peplist.loc[tmp_cleaned.index, "Quantitative_Measurement"] = median_value

			# Handle edge cases where multiple values are very close
			elif len(tmp) > 2:
				# If multiple values are close, take the median and drop the rest
				median_value = np.median(values)
				closest_to_median_idx = np.argmin(np.abs(np.array(values) - median_value))
				peplist.drop(tmp.index.difference([tmp.index[closest_to_median_idx]]), inplace=True)

	# Save filtered IEDB data for postprocessing later
	columns_tosave = [col for col in peplist.columns if col != "Flag"]
	save_dir=os.getcwd()
	save_filename="IEDB_data.csv"

	print(f'\n{start_len-len(peplist)} records dropped')

	flagged_records=pd.DataFrame(columns=columns_tosave)
	if peplist["Flag"].any():
		flagged_records=peplist.loc[(peplist['Flag']==True)].sort_values(by='Epitope_ID')
		print('{} flagged records'.format(len(flagged_records)))
		peplist=peplist.drop(flagged_records.index.tolist())
		flagged_records.drop("Flag",axis=1,inplace=True)
		flagged_fn=os.path.join(save_dir,prefix+"flagged_"+save_filename)
		flagged_records.to_csv(flagged_fn, index=False)
		print(f'Flagged epitope data located in {flagged_fn}')

	# Final output for cleaned data
	print('{} records remaining'.format(len(peplist)))
	IEDB_fn=os.path.join(save_dir,prefix+"cleaned_"+save_filename)
	print(f"Filtered IEDB data written to {IEDB_fn}")
	peplist[columns_tosave].to_csv(IEDB_fn,index=False)

	# =======Build fasta
	fasta = peplist[['Epitope_ID','Description']]
	fasta_names = '>' + fasta['Epitope_ID'].astype(str)
	#fasta_names = fasta_names.tolist()
	fasta_sequences = fasta['Description'].tolist()

	fasta_fn = os.path.join(save_dir, prefix + 'IEDB_data.fasta')

	with open(fasta_fn, 'w') as fasta_fh:
		for name, sequence in zip(fasta_names, fasta_sequences):
			if '+' not in sequence:  # Final filter: remove sequences with non-canonical amino acids
				fasta_fh.write(name + '\n')
				fasta_fh.write(sequence + '\n')
		#else:
			#print(f"Omitting epitope {n}, sequence {s}")
			#commented out for simplicity

	print(f'Epitope sequences written to {fasta_fn}')
	return fasta_fn,peplist,flagged_records

def get_peplist(allele,assay_values):
	if isinstance(allele, str):
		allele = [allele]  # Fix for single allele case
	# First we need to get the list of HLA alleles we will be retrieving data for
	print("Retrieving data from IEDB for ",end="")
	notfound=[]

	if "all" in allele:
		print("all available alleles and ",end="")
		allele=["all"]

	else:
		# If allele is not set to all, retrieve the list of alleles
		allele_list=[]
		for a in allele:
			# Check if user passes a filename
			if "@" in a:
				fname=a[1:]
				if Path(os.path.abspath(fname)).is_file():
					with open(fname,"r") as f:
						allele_list.extend(f.read().splitlines())
				else:
					notfound.append(fname)
			else:
				allele_list.append(a)
		# Error-check the allele list to ensure it is properly formatted (remove new line characters and HLA- prefixes, etc.)
		allele = [a if a.startswith("HLA-") else "HLA-" + a for a in allele]
		print(f"{len(allele)} alleles and ",end="")

	assay_values=[ele.replace("_"," ") for ele in assay_values]
	print(f"the following assay values:\n{', '.join(assay_values)}")
	if len(notfound)>0:
		notify().warn("The following allele list files were passed by the user but not located:\n{}".format(', '.join(notfound)))

	# Make sure the local copy of the IEDB is present in <MHC database location>/build. If not, download it.
	dbloc=MHCdatabase().locate
	iedb_data_fn=os.path.abspath(os.path.join(dbloc,"build","mhc_ligand_full.csv"))
	IEDB_DATA_LOC="https://www.iedb.org/downloader.php?file_name=doc/mhc_ligand_full_single_file.zip"

	if not Path(iedb_data_fn).is_file():
		notify().warn(f"Local copy of IEDB not found. Attempting download...")
		try:
			success=True
			test_download=requests.get(IEDB_DATA_LOC)
			if test_download.status_code != 200:
				success=False
		except requests.exceptions.RequestException:
			success=False
		if not success:
			notify().error("Unable to obtain local copy of IEDB. Terminating execution.")
			return False
		else:
			iedb_data_zip_fn=os.path.join(os.path.dirname(iedb_data_fn),"IEDB_data.zip")
			iedb_data_zip=requests.get(IEDB_DATA_LOC, stream=True)
			with open(iedb_data_zip_fn, mode="wb") as f:
				for chunk in iedb_data_zip.iter_content(chunk_size=1024):
					if chunk:
						f.write(chunk)
			with ZipFile(iedb_data_zip_fn,"r") as zfile:
				zfile.extractall(path=os.path.dirname(iedb_data_zip_fn))
			os.remove(iedb_data_zip_fn)
			print(f"Local copy of IEDB downloaded to {iedb_data_fn}")

	#original headers
	#cols=['Epitope IRI','PubMed ID', 'Description', 'Parent Protein', 'Parent Protein IRI', 'Method/Technique', 'Assay Group', 'Quantitative measurement', 'PDB ID', 'Allele Name', 'MHC allele class']
	#updated headers
	#cols = [('Assay ID', 'IEDB IRI'), ('Reference', 'PMID'), ('Epitope', 'Name'), ('Epitope', 'Source Molecule'), ('Epitope', 'Source Molecule IRI'), ('Epitope', 'Source Organism'), ('Assay', 'Method'), ('Assay', 'Response measured'), ('Assay', 'Units'), ('Assay', 'Quantitative measurement'), ('Assay', 'PDB ID'), ('MHC Restriction', 'Name'), ('MHC Restriction', 'Class')]

	iedb_data = pd.DataFrame()
	chunksread=0
	chunksz=500000

	with pd.read_csv(iedb_data_fn, header=[0, 1], chunksize=chunksz, low_memory=False) as reader:
		for chunk in reader:
			chunk = flatten_columns(chunk)
			if allele[0] != "all":
				chunkdata = chunk[chunk['MHC Restriction Name'].isin(allele)]
			else:
				chunkdata_A = chunk[chunk['MHC Restriction Name'].str.contains("HLA-A*", regex=False)]
				chunkdata_B = chunk[chunk['MHC Restriction Name'].str.contains("HLA-B*", regex=False)]
				chunkdata_C = chunk[chunk['MHC Restriction Name'].str.contains("HLA-C*", regex=False)]
				chunkdata = pd.concat([chunkdata_A, chunkdata_B, chunkdata_C], ignore_index=True)

			filtered = chunkdata[chunkdata["Assay Response measured"].isin(assay_values)]
			iedb_data = pd.concat([iedb_data, filtered], ignore_index=True)

			chunksread += 1
			print(f"Epitopes processed: {chunksread*chunksz:<10}Epitopes found: {len(iedb_data):<10}", end="\r")

	print()
	if len(iedb_data)==0:
		notify().error(f"No epitopes with values for {assay_values} found in the IEDB!")
		return None

	#print("=======Data before deriving new columns:")
	#print(iedb_data.columns.tolist())
	# Clean the data a little to make it compatible with clean_peplist()
	iedb_data = iedb_data.astype({'Assay ID IEDB IRI': str, 'Epitope Epitope IRI': str, 'Epitope Source Molecule IRI': str})
	iedb_data = iedb_data.copy()  # Defragment
	iedb_data = standardize_columns(iedb_data)
	iedb_data = rename_columns(iedb_data)

	#print("=======Data after standardizing and renaming columns:")
	#print(iedb_data.columns.tolist())

	iedb_data["Epitope_ID"] = iedb_data["epitope_epitope_iri"].fillna("").apply(lambda x: x.split("/")[-1] if "/" in x else np.nan)

	iedb_data["Protein_Accession"] = iedb_data["epitope_source_molecule_iri"].fillna("").apply(lambda x: x.split("/")[-1] if "/" in x else np.nan)
	iedb_data.drop(columns=['epitope_epitope_iri', 'epitope_source_molecule_iri'], inplace=True)
	#print("=======Data after new columns:")
	#print(iedb_data.columns.tolist())

	iedb_data.columns = [c.title().replace("Id", "ID").replace("Pubmed", "PubMed").replace("Mhc", "MHC").replace("Iedb", "IEDB").replace("Iri", "IRI").replace("Pdb", "PDB") for c in iedb_data.columns]
	# Drop entries with missing values
	iedb_data.dropna(subset=["Epitope_ID", "Protein_Accession"], inplace=True)
	iedb_data.reset_index(inplace=True, drop=True)

	#print("=======Cleaned IEDB data:")  # debug
	#print(iedb_data.head())
	#print("Columns in cleaned IEDB data:", iedb_data.columns.tolist())
	#print("Sample Epitope Descriptions:")
	#print(iedb_data["Description"].dropna().unique()[:5])

	# For this next part we will create a separate IEDB and fasta files for each allele/epitope combination
	# We will also combine the cleaned, flagged, and fasta data into single combined files to be stored in the working directory
	allele_list=iedb_data['MHC_Restriction_Name'].unique().tolist()
	cwd=os.getcwd()
	epitope_count=0
	fasta_filenames=[]
	all_cleaned_data=pd.DataFrame()
	all_flagged_data=pd.DataFrame()

	for a in allele_list:
		safe_allele_name = a.replace(":", "_").replace("*", "_")  # <== fix folder name
		print(f"Processing epitopes for allele {a}")

		newpath=os.path.abspath(os.path.join(cwd, safe_allele_name))
		Path(newpath).mkdir(parents=True,exist_ok=True)

		os.chdir(newpath)
		print(f"Saving files to: {newpath}")

		allele_data = iedb_data[iedb_data["MHC_Restriction_Name"] == a]

		if allele_data.empty:
			print(f"No data found for allele {a}. Skipping.")
			os.chdir(cwd)
			continue  # Skip to next allele

		tmp_data = clean_peplist(allele_data, prefix=safe_allele_name + "_")
		if tmp_data[1].empty and tmp_data[2].empty:
			print(f"No cleaned or flagged data for allele {a}. Skipping.")
			os.chdir(cwd)
			continue

		fasta_filenames.append(tmp_data[0])
		final_column_rename_map = {"Description": "Epitope_Sequence", "Epitope_Molecule_Parent": "Parent_Protein", "Epitope_Source_Organism": "Source_Organism", "MHC_Restriction_Name": "Allele", "Assay_Response_Standardized": "Assay_Response"}

		all_cleaned_data_out = tmp_data[1].rename(columns=final_column_rename_map)
		all_flagged_data_out = tmp_data[2].rename(columns=final_column_rename_map)

		final_columns = ["Epitope_Sequence", "Epitope_ID", "PubMed_ID", "Parent_Protein", "Protein_Accession", "Source_Organism", "Allele", "Assay_Method", "Assay_Response", "Quantitative_Measurement", "Assay_Units", "MHC_Restriction_Class", "Assay_PDB_ID"]

		all_cleaned_data_out = all_cleaned_data_out[final_columns]
		all_flagged_data_out = all_flagged_data_out[final_columns]

		cleaned_data_fn = os.path.join(newpath, f"{safe_allele_name}_cleaned_IEDB_data.csv")
		flagged_data_fn = os.path.join(newpath, f"{safe_allele_name}_flagged_IEDB_data.csv")

		all_cleaned_data_out.to_csv(cleaned_data_fn, index=False)
		print(f"All cleaned IEDB data written to {cleaned_data_fn}")
		all_flagged_data_out.to_csv(flagged_data_fn, index=False)
		print(f"All flagged IEDB data written to {flagged_data_fn}")

		os.chdir(cwd)
	print(f"{int(epitope_count/2)} total epitopes written to fasta files for downstream processing")

	return fasta_filenames

def fasta_rebuild(fasta_fn, seq_toAdd):

	try:
		test=int(seq_toAdd)
	except:
		test=str(seq_toAdd).lower()
		if test=='false':
			notify().notice('Running pipeline with provided fasta file {}'.format(fasta_fn))
			return fasta_fn
	else:
		if int(seq_toAdd)==0:
			notify().notice('Running pipeline with provided fasta file {}'.format(fasta_fn))
			return fasta_fn

	if not os.path.isfile(os.path.abspath(fasta_fn)):
		sys.exit(notify().error('.fasta file {} does not exist!'.format(fasta_fn)))
	elif not os.path.isfile(seq_toAdd):
		sys.exit(notify().error('Curated sequences file {} does not exist!'.format(seq_toAdd)))

	seq_fh=open(seq_toAdd,'r')
	seq_data=seq_fh.readlines()[1::]
	seq_fh.close()

	fasta_fh=open(fasta_fn,'a')
	for i,l in enumerate(seq_data):
		tmp_data = l.split(',')
		if i==len(seq_data)-1:
			fasta_fh.write('>{}\n{}'.format(tmp_data[0],tmp_data[2]))
		else:
			fasta_fh.write('>{}\n{}\n'.format(tmp_data[0],tmp_data[2]))
	fasta_fh.close()

	print('Curated sequences added to {}'.format(fasta_fn))

	return fasta_filenames, all_cleaned_data, all_flagged_data

def add_NCAA(fasta_fn,params,position=False):

	fasta_fh = open(fasta_fn,"r")
	fasta_data = fasta_fh.readlines()
	fasta_fh.close()

	if not os.path.isfile(params):
		sys.exit(notify().error("Params file {} does not exist!".format(params)))
	else:
		params_fh=open(params,"r")
		ncaa_code=params_fh.readline().strip()
		ncaa_code=ncaa_code[-3::]
		print("NCAA 3-letter code: {}".format(ncaa_code))

	set_pos=False
	if position:
		try:
			int(position)
		except:
			notify().warn("{} is not a valid integer position. Ignoring in favor of default NCAA placeholder X".format(position))
		else:
			position=int(position)
			set_pos=True

	fasta_fh=open(fasta_fn,"w")
	numlines=len(fasta_data)
	seqcount=0
	for i,l in enumerate(fasta_data):

		tmpl=list(l.strip())

		if ">" not in tmpl and set_pos: #Make sure we have a sequence
			if position<=len(tmpl):
				tmpl[position-1]="X[{}]".format(ncaa_code)
				tmpl="".join(tmpl)
				fasta_fh.write(tmpl)
				seqcount+=1
				if i+1!=numlines:
					fasta_fh.write("\n")
			else:
				notify().warn("Position {} is out of range for sequence {} of length {}".format(position, "".join(tmpl), len(tmpl)))
				fasta_fh.write("".join(tmpl))
				if i+1!=numlines:
					fasta_fh.write("\n")
		elif ">" not in tmpl and not set_pos and "X" in tmpl: #If no position to replace is set, replace default placeholder value ("X")
			tmpl="".join(tmpl)
			tmpl=tmpl.replace("X","X[{}]".format(ncaa_code))
			fasta_fh.write(tmpl)
			seqcount+=1
			if i+1!=numlines:
					fasta_fh.write("\n")
		else:
			fasta_fh.write("".join(tmpl))
			if i+1!=numlines:
					fasta_fh.write("\n")

	fasta_fh.close()
	notify().notice("NCAA '{}' added to {} sequences".format(ncaa_code,seqcount))

	return


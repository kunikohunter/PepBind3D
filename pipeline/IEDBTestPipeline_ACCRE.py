def stats_from_scorefile(scorefile, sortby="I_sc", topn=5):

	import pandas as pd
	import math
	import numpy as np
	from formats import progressBar
	# Assumes scorefile with "Epitope_ID" and "Quantitative_measurement" columns as generated by postprocessing_affinity

	prog_bar=progressBar(blen=30,bcolor1="red")

	score_data=pd.read_csv(scorefile)
	new_data=pd.DataFrame(columns=score_data.columns.tolist())
	score_data.sort_values(["Epitope_ID", sortby], inplace=True)

	enames=score_data["Epitope_ID"].unique().tolist()
	enames=list(set(score_data["Epitope_ID"].tolist()))
	
	average_reu=[]
	std_reu=[]
	BA_logIC50=[]

	resolution_reu=100 # Data to determine how many REU thresholds we will calculate statistics for

	# Most relevant thresholds for statistics calculations. <50nm is a strong binder, >50<500 is a weak binder, and >500 is a nonbinder.
	thresholds_logIC50=[math.log10(50), math.log10(500)]

	prog_bar.update(0.1, msg=f"Computing average binding affinities for top {topn} models")
	for e in enames:
		tmp_data=score_data.loc[(score_data["Epitope_ID"]==e)]
		new_data=pd.concat([new_data,tmp_data.iloc[:(topn+1)]],ignore_index=True) #for output file
		average_reu.append(tmp_data[sortby].iloc[:(topn+1)].mean()) #averages
		std_reu.append(tmp_data[sortby].iloc[:(topn+1)].std()) #stdevs
		BA_logIC50.append(math.log10(tmp_data["Quantitative_Measurement"].iloc[0])) #all values for a given epitope should be identical
	prog_bar.update(0,pmsg=f"Computed average binding affinities for top {topn} models")

	thresholds_reu=np.linspace(min(average_reu)+1,max(average_reu)-1,num=resolution_reu)

	fn_suffix="sortby-{}_topn-{}".format(sortby,topn)
	graph_fn="graphData_{}.csv".format(fn_suffix)
	prog_bar.update(0.1,msg="Writing average REU values for top {} models and corresponding binding affinity to {}".format(topn,graph_fn))

	pd.DataFrame({"Binding Affinity (log10(IC50))": BA_logIC50, "Average REU": average_reu, "STDEV": std_reu}).to_csv(graph_fn, index=False)

	prog_bar.update(0,pmsg=f"ROC statistics written to {graph_fn}")

	# What we need: average value for each epitope, along with +/-SD
	# Threshold value for "strong" vs "weak" binder
	# For each threshold, build an ROC and output to a file named threshold_ROC.csv
	# Also output a file that has test statistics for each threshold:
	# 	TP, FP, TN, FN, PPV, NPV, FDR, +LR, -LR, prevalence, accuracy
	#   ROC x axis (1-specificity, or FP/FP+TN)
	# 	ROC y axis (sensitivity, or TP/TP+FN)

	# Now for each threshold calculate the statistics above. First classify all
	# of our values as "BINDER" or "NONBINDER" based on predefined log10(IC50) cutoffs (this is the true value). Then, iterate through the rosetta REU thresholds and calc the table of stats above. For each threshold classifier, find the optimal AUC value (i.e. the highest) and report the statistics for the test as shown.

	AUC=[]
	prevalence=[]
	optimal_REU_thresh_energy=[]
	optimal_REU_thresh_accuracy=[]
	for ind,thresh in enumerate(thresholds_logIC50):
		TP_rate=[]
		TN_rate=[]
		FP_rate=[]
		FN_rate=[]
		PPV=[]
		NPV=[]
		FDR=[]
		LR_pos=[]
		LR_neg=[]
		accuracy=[]
		jstat=[]
		prog_bar.update(0.2,msg="Computing statistics for log10(IC50) threshold {}".format(thresh))
		thresh_true = []
		for i in range(0,len(enames)): # Determine binder classification (true positives)
			if BA_logIC50[i]<=thresh:
				thresh_true.append(True)
			else:
				thresh_true.append(False)
		
		prevalence.append(sum(thresh_true)/len(thresh_true))
		
		# Define x,y pairs for ROC:
		one_minus_spec=[]
		sens=[]
		for reu_cutoff in thresholds_reu: # Now determine ROC and AUC
			# For each cutoff tested we need an (x,y) pair for the ROC
			TP = []
			TN = []
			FP = []
			FN = []
			for i in range(0,len(enames)):
				TP.append(thresh_true[i] and (average_reu[i]<=reu_cutoff)) 
				TN.append(thresh_true[i]==False and (average_reu[i]>reu_cutoff))
				FP.append(thresh_true[i]==False and (average_reu[i]<=reu_cutoff))
				FN.append(thresh_true[i] and (average_reu[i]>reu_cutoff))
			
			FP_sum=sum(FP)
			TN_sum=sum(TN)
			TP_sum=sum(TP)
			FN_sum=sum(FN)
			# print(reu_cutoff)
			# print("FP: {}".format(FP_sum))
			# print("TN: {}".format(TN_sum))
			# print("TP: {}".format(TP_sum))
			# print("FN: {}".format(FN_sum))
			one_minus_spec.append(FP_sum/(FP_sum+TN_sum))

			calc=True
			try:
				TP_sum/(TP_sum+FN_sum)
			except ZeroDivisionError:
				TP_rate.append(np.inf)
				sens.append(np.inf)
				FN_rate.append(np.inf)
				calc=False
			if calc:
				sens.append(TP_sum/(TP_sum+FN_sum))
				TP_rate.append(TP_sum/(TP_sum+FN_sum)) # Recall, same as sensitivity
				FN_rate.append(FN_sum/(FN_sum+TP_sum))
			
			FP_rate.append(FP_sum/(FP_sum+TN_sum))
			TN_rate.append(TN_sum/(TN_sum+FP_sum)) # Specificity
			

			PPV.append(TP_sum/(TP_sum+FP_sum)) # Precision
			NPV.append(TN_sum/(TN_sum+FN_sum))
			FDR.append(FP_sum/(FP_sum+TP_sum))
			LR_pos.append(TP_rate[-1]/FP_rate[-1])
			LR_neg.append(FN_rate[-1]/TN_rate[-1])
			accuracy.append((TP_sum+TN_sum)/(len(thresh_true)))
			jstat.append(TP_rate[-1]+TN_rate[-1]-1)

		ROC_xy=sorted(zip(one_minus_spec,sens), key=lambda k: k[0])
		tmp=0
		for i in range(0,len(sens)-1):
			x1=ROC_xy[i][0]
			x2=ROC_xy[i+1][0]
			y1=ROC_xy[i][1]
			y2=ROC_xy[i+1][1]
			tmp=tmp+(x2-x1)*(y1+0.5*(y2-y1))
		
		AUC.append(tmp)
		tmp_stats={"REU Threshold": thresholds_reu, "TP (Recall)": TP_rate, "FP": FP_rate, "TN (Specificity)": TN_rate, "FN": FN_rate, "PPV (Precision)": PPV, "NPV": NPV, "FDR": FDR, "Positive Likelihood Ratio": LR_pos, "Negative Likelihood Ratio": LR_neg, "Accuracy": accuracy, "J-statistic": jstat}
		tmp_stats_df=pd.DataFrame(tmp_stats)
		tmp_fn="IC50-{}_statistics_{}.csv".format(round(10**thresh), fn_suffix)
		prog_bar.update(0.2,pmsg="Writing statisitcs for IC50 {}nm to {}".format(round(10**thresh), tmp_fn))
		tmp_stats_df.to_csv(tmp_fn, index=False)

		# Find the optimal REU threshold based on accuracy:
		optimal_REU_thresh_tmp=max(zip(thresholds_reu, accuracy), key=lambda x: x[1])
		optimal_REU_thresh_energy.append(optimal_REU_thresh_tmp[0])
		optimal_REU_thresh_accuracy.append(optimal_REU_thresh_tmp[1])

	thresholds_fn="summaryStatistics_{}.csv".format(fn_suffix)
	prog_bar.update(0.2,msg="Writing summary statistics for all thresholds to {}".format(thresholds_fn))

	pd.DataFrame({"Thresholds (log10(IC50)": [round(10**x) for x in thresholds_logIC50], "ROC CDF (AUC)": AUC, "Optimal {} Threshold".format(sortby): optimal_REU_thresh_energy, "Accuracy": optimal_REU_thresh_accuracy}).to_csv(thresholds_fn, index=False)

	return


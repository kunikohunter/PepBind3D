def make_batch(fasta_fn, size=None):
	size = size or 25 # if size is None or 0, default to 25
	# Open file, read in sequence data and names as a dict, then define batch size
	with open(fasta_fn) as fh:
		lines = fh.readlines()
	fnames = lines[0::2]
	seqs = lines[1::2]

	# Initialize counters for batch and directory
	b_count = size  # Batch count iterator - keeps track of whether we need to make a new batch directory
	b_dir_count = 1  # Batch directory count - starts with 1 and adds 1
	base_dir = os.path.dirname(fasta_fn)  # Get the base directory where the FASTA file is located

	# Extract base name of the input FASTA file (without the '.fasta' extension)
	fasta_base_name = os.path.splitext(os.path.basename(fasta_fn))[0]

	# Construct the output directory structure
	output_dir = os.path.join(base_dir, 'output')  # Base output directory (e.g., 'output')
	os.makedirs(output_dir, exist_ok=True)  # Make the output directory if it doesn't exist

	# Causing problems with nested folders and batch1 overwriting
	# Folder for allele (e.g., HLA-A_01_01)
	#allele_folder = os.path.basename(base_dir)
	# Path for batch directories
	#batch_dir = os.path.join(output_dir, allele_folder, f'batch{b_dir_count}')

	# Use the base name of the input FASTA file as part of the batch directory name
	batch_dir = os.path.join(output_dir, f'{fasta_base_name}_batch{b_dir_count}')
	os.makedirs(batch_dir, exist_ok=True)  # Create the first batch directory

	tmp_fn = os.path.abspath(os.path.join(batch_dir, f'batch{b_dir_count}.fasta'))
	tmp_fh = open(tmp_fn, "w")

	seqdata = zip(fnames, seqs)
	blist = [tmp_fn]  # Keep track of our FASTA files

	for ind, (name, seq) in enumerate(seqdata):
		if ind > 0 and ind % size == 0:
			tmp_fh.close()
			b_dir_count += 1
			batch_dir = os.path.join(output_dir, f'{fasta_base_name}_batch{b_dir_count}')
			os.makedirs(batch_dir, exist_ok=True)

			tmp_fn = os.path.abspath(os.path.join(batch_dir, f'batch{b_dir_count}.fasta'))
			tmp_fh = open(tmp_fn, "w")
			blist.append(tmp_fn)
		tmp_fh.write(name)
		tmp_fh.write(seq)
	tmp_fh.close()
	return blist


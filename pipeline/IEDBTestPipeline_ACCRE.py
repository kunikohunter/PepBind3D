def thread_template(input_fasta, db, ROSETTA_PATH, params=False, user_defined_receptor=None, ignore_perfect_match=False, find_worst_template=False):
	# Subroutine that takes in an input peptide, path to database with aligned peptide/MHC complexes, and desired allele
	# Finds a matching peptide with the best sequence identity then threads the input peptide onto the corresponding model
 	# Takes the threaded model and writes a rosetta_scripts.xml file to generate an input structure for flexpepdock refinement
 	# Optionally takes in a params file (with the position denoted by "X[NCAA]" in the input_fasta file), and incorporates the NCAA into the final starting model by mutating the amino acid at the appropriate position.
 	# Fasta files with NCAA should be formatted per Rosetta guidelines (i.e., NCAA should be designated "X[NCAA_name]")

 	# Create the allele - we will need to make sure it has a receptor present in the database as well
 	allele=db.allele
 	if user_defined_receptor!=None and Path(user_defined_receptor).is_file():
 		chk_success=db.set_allele(allele, build_receptor=False)
 	else:
 		chk_success=db.set_allele(allele)# This will automatically build the receptor if it is not present and create a list of alleles in the structure database to use as peptide backbone templates. Building a receptor with AlphaFold2 could take upwards of ~1h
 	if not chk_success:
 		notify().error(f"Failed to set allele to {allele}")
 		#print(f"DEBUG: db.set_allele returned {chk_success}")
 		return False

	# Retrieve the peptide sequences in the structural database for either the allele or (if unavailable) its next nearest sequence neighbor
 	struct_data_fn=os.path.join(db.locate,"database.info")
 	if Path(struct_data_fn).is_file():
 		struct_data=pd.read_csv(struct_data_fn)
 	else:
 		notify().error(f"Unable to locate {struct_data_fn}! Does it exist?")
 		#print(f"DEBUG: Checking for {struct_data_fn} -> Exists? {Path(struct_data_fn).is_file()}")
 		return False

 	# Retrieve the default receptor location
 	receptor_default=db.receptor

 	# Import the fasta file for the sequence to thread
 	input_record = SeqIO.read(input_fasta, "fasta")
 	input_record_originalSeq = input_record.seq

 	# Handle NCAA sequences if present
 	if "X" in input_record.seq:
 		if not params:
 			notify().error(f"NCAA placeholder 'X' found in {input_fasta}, but no params file provided.")
 			#print(f"DEBUG: NCAA handling - params provided? {params}")
 			return False
 		else:
 			with open(os.path.abspath(params), "r") as pfile:
 				NCAA_name = pfile.readline().strip()[-3:]
 			input_record.seq = Seq(str(input_record.seq).replace(f"[{NCAA_name}]", ""))

 	# Template selection logic
 	to_omit = ["self"] if ignore_perfect_match else []
 	template_id_method = "worst" if find_worst_template else "best"

 	queryseq = str(input_record.seq) if "X" in input_record.seq else str(input_record_originalSeq)

 	# Retrieve multiple ranked templates
 	template_candidates = db.get_peptide_template(queryseq, method=template_id_method, omit=to_omit)
 	if not template_candidates:
 		notify().error(f"DEBUG: No valid templates found for sequence: {queryseq}")
 		print(f"DEBUG: Found {len(template_candidates)} templates for {queryseq}")
 		return False

 	# Define parent directory and log file
 	parent_dir = os.path.abspath(os.path.dirname(input_fasta))
 	log_file = os.path.join(parent_dir, f"{os.path.basename(input_fasta)[:-6]}_ROSETTA.log")
 	print(f"DEBUG: Log file will be saved to {log_file}")

 	print(f"DEBUG: Found {len(template_candidates)} template(s) for sequence {queryseq}")
 	if len(template_candidates) == 0:
 		notify().error(f"No templates found for {queryseq}")
 		return False

 	# Try each template until one succeeds
 	for best_pdb in template_candidates:
 		best_pdb_fn = os.path.abspath(os.path.join(db.locate, "templates", best_pdb + ".pdb"))
 		XML_filename = os.path.join(parent_dir, f"flexpepdock_input_{os.path.basename(input_fasta)[:-6]}.xml")

 		# Retrieve template sequence
 		best_sequence_data = db.query_mhc_database(gettemplate=best_pdb, quiet=True)[0]
 		best_sequence = best_sequence_data["Epitope_Description"]

 		# Get chain information
 		db_records = pd.read_csv(os.path.join(db.locate, "database.info"))
 		pChain = db_records["Antigen_PDB_Chain(s)"].loc[db_records["PDB_ID"] == best_pdb].values[0]
 		mhcChain = db_records["MHC_PDB_Chain1"].loc[db_records["PDB_ID"] == best_pdb].values[0]

 		# STEP 1: Generate XML for SimpleThreadingMover
 		root = ET.Element("ROSETTASCRIPTS")

 		scorefxns = ET.SubElement(root, "SCOREFXNS")
 		ET.SubElement(scorefxns, "ScoreFunction", name="score", weights="ref2015")

 		movers = ET.SubElement(root, "MOVERS")
 		protocols = ET.SubElement(root, "PROTOCOLS")

 		if "X" in input_record.seq:
 			modified_seq = input_record.seq.replace("X", "X[KIS]")
 		else:
 			modified_seq = input_record.seq
 		if "X" in input_record.seq and not params:
 			print(f"DEBUG: Params file missing for NCAA sequence {input_fasta}")
 			notify().error(f"NCAA placeholder 'X' found in {input_fasta}, but no params file provided.")
 			return False


 		start_pos = "1" if not pChain or pChain == "0" else f"1{pChain}"  # Default to "1" if pChain is empty or invalid
 		ET.SubElement(movers, "SimpleThreadingMover", name="threadModel", pack_neighbors="1", 		start_position=start_pos, thread_sequence=modified_seq, skip_unknown_mutant="1", pack_rounds="1")
 		ET.SubElement(protocols, "Add", mover="threadModel")
 		#print(f"DEBUG: Assigned start_position='{start_pos}' in XML")  # Debugging

 		# STEP 1b: Mutate NCAA if present
 		if params:
 			params_path = os.path.abspath(params)  # Ensure absolute path
 			params_dest = os.path.join(parent_dir, os.path.basename(params))  # Destination in working dir

 			# Copy NCAA params file to working directory
 			shutil.copyfile(params_path, params_dest)

 			# Copy associated rotamer file if it exists
 			rotamers_fn = None
 			with open(params_path, "r") as pfile:
 				last_line = pfile.readlines()[-1].strip()  # Read last line
 				#print(f"DEBUG: Last line of params file -> {last_line}")
 				if last_line.startswith("PDB_ROTAMERS"):  # Ensure correct line
 					rotamers_fn = os.path.join(os.path.dirname(params_path), last_line.split(" ")[1])

 			if rotamers_fn:
 				print(f"DEBUG: Searching for rotamer file at {rotamers_fn}")
 			# If the rotamer file exists, copy it
 			if rotamers_fn and os.path.exists(rotamers_fn):
 				shutil.copyfile(rotamers_fn, os.path.join(parent_dir, os.path.basename(rotamers_fn)))
 				#print(f"DEBUG: Copied NCAA rotamer file {rotamers_fn} to {parent_dir}")
 			else:
 				print("WARNING: No valid rotamer file found! NCAA mutation may fail. Expected at {rotamers_fn}")
 			if os.path.exists(rotamers_fn):
 				shutil.copyfile(rotamers_fn, os.path.join(parent_dir, os.path.basename(rotamers_fn)))
 				#print(f"DEBUG: Copied NCAA rotamer file to {parent_dir}")
 			for i, AA in enumerate(input_record.seq):
 				if AA == "X":
 					tmp_pos = i + 1
 					ET.SubElement(protocols, "Add", mover=f"mutateRes_{tmp_pos}")
 					ET.SubElement(movers, "MutateResidue", name=f"mutateRes_{tmp_pos}",
                                  target=f"{tmp_pos}{pChain}", new_res=NCAA_name)
 			if 'args' not in locals():
 				args = []
 			args.extend(["-extra_res_fa", os.path.abspath(params)])

 		# STEP 2: Delete overhanging residues
 		N = len(best_sequence) - len(input_record.seq)

 		# Ensure chain alignment
 		from Bio.PDB import PDBParser
 		pdb_parser = PDBParser(QUIET=True)
 		structure = pdb_parser.get_structure("template", best_pdb_fn)
 		model = structure[0]
 		chain = model[mhcChain]
 		template_rescount = sum(1 for _ in chain)
 		# Highest residue NUMBER in the MHC chain. This differs from the residue
 		# COUNT whenever the chain has numbering gaps (unresolved residues), and
 		# the receptor trim below needs the number, not the count: deleting
 		# 182..count leaves every residue numbered above the count behind as a
 		# spurious extra chain.
 		template_resmax = max((r.id[1] for r in chain if r.id[0] == " "), default=template_rescount)

 		receptor_default = db.receptor

 		replace_receptor_fn = os.path.abspath(user_defined_receptor) if user_defined_receptor and Path(user_defined_receptor).is_file() else receptor_default

 		#print(f"DEBUG: user_defined_receptor = {user_defined_receptor}")
 		#print(f"DEBUG: receptor_default = {receptor_default}")
 		#print(f"DEBUG: using receptor file -> {replace_receptor_fn}")

 		new_receptor_fn = os.path.join(parent_dir, "tmp_receptor.pdb")
 		#print(f"DEBUG: new_receptor_fn assigned -> {new_receptor_fn}")

 		if not Path(replace_receptor_fn).is_file():
 			print(f"ERROR: Expected receptor file {replace_receptor_fn} does not exist!")
 			return False  # Exit early if receptor file is missing

 		try:
 			new_receptor = pdb_parser.get_structure("defaultReceptor", replace_receptor_fn)
 		except Exception as e:
 			print(f"ERROR: pdb_parser.get_structure failed! Exception: {e}")
 			return False

 		io = PDBIO()
 		found_chain_A = False

 		for chain in new_receptor.get_chains():
 			print(f"DEBUG: Checking chain {chain.get_id()} in new_receptor")
 			if chain.get_id() == "A":
 				found_chain_A = True
 				io.set_structure(chain)
 				io.save(new_receptor_fn)
 				print(f"Successfully saved receptor to {new_receptor_fn}")

 		if not found_chain_A:
 			print(f"ERROR: Chain 'A' not found in receptor structure!")
 			return False

 		if not os.path.exists(new_receptor_fn):
 			print(f"ERROR: new_receptor_fn {new_receptor_fn} does not exist before using it.")
 			return False

 		structure = pdb_parser.get_structure("receptor", new_receptor_fn)
 		model = structure[0]
 		chain = model["A"]
 		receptor_rescount = sum(1 for _ in chain)

 		# Ensure deletion only delete residues within the valid range
 		if N > 0:
 			delete_start = len(input_record.seq) + 1
 			delete_end = min(len(best_sequence), template_rescount)

 			if delete_start <= template_rescount:
 				ET.SubElement(protocols, "Add", mover="deleteRes")
 				ET.SubElement(movers, "DeleteRegionMover", name="deleteRes", start=f"{delete_start}{pChain}", end=f"{delete_end}{pChain}")

 		# STEP 3: Add receptor
 		# If the template is longer, remove extra residues
 		resdiff = template_rescount - receptor_rescount
 		if resdiff > 0:
 			# Trim to the highest residue NUMBER, not the residue count. On a
 			# chain with numbering gaps count < max number, so trimming to the
 			# count leaves every residue numbered above it behind as a spurious
 			# chain of untrimmed receptor whose size equals the gap count.
 			trim_end = template_resmax
 			ET.SubElement(protocols, "Add", mover="deleteRes_receptor")
 			ET.SubElement(movers, "DeleteRegionMover", name="deleteRes_receptor",
                  start=f"{receptor_rescount + 1}{mhcChain}",
                  end=f"{trim_end}{mhcChain}", rechain="1")

 		chaindict = {chr(i): i - 64 for i in range(65, 91)}
 		mhcChain = db_records["MHC_PDB_Chain1"].loc[db_records["PDB_ID"] == best_pdb].values[0]
 		if mhcChain in chaindict:
 			chain_toSwap = chaindict.get(mhcChain, 1)
 		else:
 			notify().error(f"Unrecognized chain ID '{mhcChain} in {best_pdb}. Defaulting to 'A'.")
 			chain_toSwap = 1

 		ET.SubElement(protocols, "Add", mover="addReceptor")
 		ET.SubElement(movers, "AddChain", name="addReceptor", file_name=new_receptor_fn, swap_chain_number=str(chain_toSwap))

 		# STEP 4: FastRelax after prepack
 		ET.SubElement(protocols,"Add", mover="fastrelax")
 		ET.SubElement(movers, "FastRelax", name="fastrelax", repeats="5", scorefxn="score")

 		# STEP 5: Run FlexPepDock prepack
 		ET.SubElement(protocols, "Add", mover="prepack")
 		ET.SubElement(movers, "FlexPepDock", name="prepack", ppk_only="1")
    
 		# Write XML file
 		#print(f"DEBUG: Preparing to write XML file at {XML_filename}")
 		os.makedirs(os.path.dirname(XML_filename), exist_ok=True)
 		xmltree = ET.ElementTree(root)
 		ET.indent(xmltree, space='    ')
 		#print(f"DEBUG: Writing XML file now...")
 		xmltree.write(XML_filename)

 		# Ensure XML file was created
 		if os.path.exists(XML_filename):
 			print(f"DEBUG: XML file successfully written at {XML_filename}")
 		else:
 			print(f"DEBUG: XML failed to write at {XML_filename}")
 			return False

 		###### Debugging
 		required_files = {
 			"Template PDB": best_pdb_fn,
 			"XML Protocol": XML_filename,
 			"Receptor PDB": replace_receptor_fn if user_defined_receptor else "N/A",
 		}
 		if params:
 			required_files["Params File"] = params

 		for name, file in required_files.items():
 			if file != "N/A" and not os.path.exists(file):
 				print(f"ERROR: {name} not found -> {file}")
 				return False  # Stop execution if a required file is missing

 		print("All required files exist. Proceeding with Rosetta...", flush=True)

 		# Run Rosetta 
 		notify().notice(f"Running Rosetta with template {best_pdb}")
        
 		args = []
 		#log_file = os.path.join(parent_dir, f"{os.path.basename(input_fasta)[:-6]}_rosetta.log")
 		args = [f"{ROSETTA_PATH}/source/bin/rosetta_scripts.linuxgccrelease", "-s", best_pdb_fn, "-parser:protocol", XML_filename, "-database", f"{ROSETTA_PATH}/database", "-overwrite", "-out:level", "300"]
 		# "-mute", "all"
 		# Load depositor coordinates flagged occupancy=0. Rosetta drops
 		# zero-occupancy atoms by default, so a template whose peptide has an
 		# unresolved middle loads short and the threaded query is silently
 		# truncated (1QR1: 9 peptide CA but only 6 Rosetta-loadable, so a 9-mer
 		# threads as 6). The disordered coordinates are still a valid starting
 		# placement: the anchors are resolved and FastRelax + FlexPepDock
 		# -pep_refine resample the peptide anyway.
 		args.extend(["-ignore_zero_occupancy", "false"])
 		if params and os.path.exists(params):
 			args.extend(["-extra_res_fa", os.path.abspath(params)])

 		print(f"DEBUG: Running Rosetta with command:\n{' '.join(args)}", flush=True)

 		try:
 			with open(log_file, "w") as f:
 				print(f"DEBUG: Running Rosetta, logging to {log_file}", flush=True)
 				p = subprocess.run(args, stdout=f, stderr=f)

 			# Rename the output .pdb file
 			output_pdb_fn = os.path.join(parent_dir, "{}_0001.pdb".format(best_pdb))

 			# Check if Rosetta produced the expected PDB file
 			if os.path.exists(output_pdb_fn):
 				print(f"\n{output_pdb_fn} saved and ready for production.", flush=True)

 				# Rename the output .pdb file
 				output_fn_new = os.path.join(parent_dir, "{}_input.pdb".format(os.path.basename(input_fasta)[0:-6]))

 				# Ensure old file exists before renaming to avoid errors
 				if os.path.exists(output_pdb_fn):
 					shutil.move(output_pdb_fn, output_fn_new)
 					print(f"Renamed {output_pdb_fn} to {output_fn_new}")
 					return output_fn_new  # Return the renamed PDB file
 				else:
 					print(f"Warning: {output_pdb_fn} not found. Renaming skipped.")
 					return output_pdb_fn  # Return the original file if renaming failed
 			else:
 				notify().error(f"Expected output {output_pdb_fn} not found. Check Rosetta output.")

 		except subprocess.CalledProcessError:
 			print(f"Rosetta failed with template {best_pdb}. Trying next template...")
 	# If no templates worked
 	notify().error(f"All templates failed for {queryseq}. Skipping.")
 	return False

